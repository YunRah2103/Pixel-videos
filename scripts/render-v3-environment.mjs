import {spawnSync} from 'node:child_process';
import {mkdirSync,existsSync,readFileSync,writeFileSync} from 'node:fs';
mkdirSync('out',{recursive:true});
const run=(cmd,args)=>{const p=spawnSync(cmd,args,{stdio:'inherit'});if(p.status!==0)throw Error(cmd+' failed '+p.status)};
const npx=process.platform==='win32'?'npx.cmd':'npx';
const low='out/sunset-harbor-v3-environment-lowres.mp4',dest='out/sunset-harbor-v3-environment-1080p.mp4';
run(npx,['remotion','render','src/index.ts','HarborEnvironmentProof',low,'--codec','h264']);
const embedded='assets/sunset-jazz-excerpt.m4a.b64';
const music=existsSync('assets/sunset-jazz-excerpt.m4a')?'assets/sunset-jazz-excerpt.m4a':existsSync(embedded)?'out/sunset-jazz-excerpt.m4a':null;
if(music?.startsWith('out/'))writeFileSync(music,Buffer.from(readFileSync(embedded,'utf8').replace(/\s/g,''),'base64'));
const args=['-hide_banner','-loglevel','error','-y','-i',low];
if(music)args.push('-i',music);
args.push('-map','0:v:0');
if(music)args.push('-map','1:a:0');
args.push('-vf','scale=1080:1920:flags=neighbor,format=yuv420p','-c:v','libx264','-preset','medium','-crf','17','-pix_fmt','yuv420p','-r','30');
if(music)args.push('-af','afade=t=in:st=0:d=0.24,afade=t=out:st=10.65:d=1.35','-c:a','aac','-b:a','160k');
args.push('-t','12','-movflags','+faststart',dest);run('ffmpeg',args);
const p=spawnSync('ffprobe',['-v','error','-count_frames','-select_streams','v:0','-show_entries','stream=codec_name,width,height,r_frame_rate,nb_read_frames:format=duration','-of','json',dest],{encoding:'utf8'});
if(p.status!==0)throw Error('ffprobe failed');
const j=JSON.parse(p.stdout),v=j.streams[0];
if(v.codec_name!=='h264'||v.width!==1080||v.height!==1920||v.r_frame_rate!=='30/1'||Number(v.nb_read_frames)!==360||Math.abs(Number(j.format.duration)-12)>.13)throw Error('Invalid video '+p.stdout);
run('ffmpeg',['-v','error','-i',dest,'-f','null','-']);
console.log(JSON.stringify({verified:true,output:dest,video:v,duration:j.format.duration,audio:!!music},null,2));
