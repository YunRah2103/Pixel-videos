#!/usr/bin/env python3
"""Rebuild src/scenes/nightDriveData.ts from a reference clip.

The reference is a 1080x1920 clip drawn on a 180x320 pixel grid (6x nearest
upscale). Every 6x6 block is collapsed to one palette-indexed pixel so the scene
can be redrawn crisply by Remotion at 180x320.

    python3 tools/extract_night_drive.py REFERENCE.mp4

Needs ffmpeg and numpy (+ Pillow not required).
"""
import subprocess
import sys
from pathlib import Path

import numpy as np

W, H, SCALE = 180, 320, 6
MERGE = 14          # colours closer than this (L-inf) share one palette entry
BOX = (62, 156, 112, 180)  # x0, y0, x1, y1 of the animated passengers
CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
OUT = Path(__file__).resolve().parent.parent / 'src' / 'scenes' / 'nightDriveData.ts'


def read_grids(src: str) -> np.ndarray:
    raw = subprocess.run(
        ['ffmpeg', '-v', 'error', '-i', src, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'],
        check=True, stdout=subprocess.PIPE).stdout
    frames = np.frombuffer(raw, np.uint8).reshape(-1, H * SCALE, W * SCALE, 3)
    out = []
    for f in frames:
        blocks = f.astype(np.int32).reshape(H, SCALE, W, SCALE, 3).transpose(0, 2, 1, 3, 4)
        out.append(np.median(blocks.reshape(H, W, SCALE * SCALE, 3), axis=2).astype(np.uint8))
    return np.stack(out)


def build_palette(samples):
    colours, counts = np.unique(np.concatenate([s.reshape(-1, 3) for s in samples]), axis=0, return_counts=True)
    palette = []
    for i in np.argsort(-counts):
        c = colours[i].astype(int)
        if not any(np.abs(c - p).max() <= MERGE for p in palette):
            palette.append(c)
    return np.array(palette)


def index(img, palette):
    d = np.abs(img.astype(int)[:, :, None, :] - palette[None, None]).max(axis=3)
    return d.argmin(axis=2)


def main():
    grids = read_grids(sys.argv[1])
    x0, y0, x1, y1 = BOX
    # Captions are drawn in code, so the backdrop comes from a caption-free frame.
    base = grids[0]
    palette = build_palette([base] + [g[y0:y1, x0:x1] for g in grids])
    assert len(palette) <= len(CHARS), len(palette)
    bg = index(base, palette)

    variants, seq = [], []
    for g in grids:
        v = ''.join(CHARS[i] for i in index(g[y0:y1, x0:x1], palette).ravel())
        if v not in variants:
            variants.append(v)
        seq.append(variants.index(v))

    rows = [''.join(CHARS[i] for i in r) for r in bg]
    hexes = ['#%02x%02x%02x' % tuple(c) for c in palette]
    # run-length encode the per-frame variant sequence: [variant, frames]
    rle = []
    for s in seq:
        if rle and rle[-1][0] == s:
            rle[-1][1] += 1
        else:
            rle.append([s, 1])

    lines = [
        '// Generated by tools/extract_night_drive.py -- do not edit by hand.',
        f'export const GRID = {{width: {W}, height: {H}}};',
        f'export const PALETTE = {hexes!r};'.replace("'", '"'),
        f'export const CHARS = "{CHARS}";',
        'export const BACKDROP: string[] = [',
        *[f'  "{r}",' for r in rows],
        '];',
        f'export const PASSENGER_BOX = {{x: {x0}, y: {y0}, w: {x1 - x0}, h: {y1 - y0}}};',
        'export const PASSENGER_VARIANTS: string[] = [',
        *[f'  "{v}",' for v in variants],
        '];',
        '// [variant index, number of frames] pairs covering every video frame',
        f'export const PASSENGER_TIMELINE: [number, number][] = {rle!r};'.replace("'", '"'),
        '',
    ]
    OUT.write_text('\n'.join(lines))
    err = np.abs(palette[bg].astype(int) - base.astype(int)).mean()
    print(f'palette={len(palette)} variants={len(variants)} steps={len(rle)} mean err={err:.2f} -> {OUT}')


if __name__ == '__main__':
    main()
